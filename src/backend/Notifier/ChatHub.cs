using Microsoft.AspNetCore.SignalR;

namespace Notifier
{
    [Microsoft.AspNetCore.Authorization.Authorize]
    public class ChatHub(Notifications.INotificationRecipientScope recipientScope) : Hub
    {
        public override async Task OnConnectedAsync()
        {
            var claim = Context.User?.FindFirst(System.Security.Claims.ClaimTypes.NameIdentifier)?.Value;
            var stamp = Context.User?.FindFirst("AspNet.Identity.SecurityStamp")?.Value;
            var group = Context.User?.Identity?.IsAuthenticated == true && int.TryParse(claim, out var id) && id > 0
                ? await recipientScope.GetGroupAsync(id, Context.ConnectionAborted, stamp) : null;
            if (group is null)
            {
                Context.Abort();
                throw new HubException("Your session is no longer available.");
            }
            await Groups.AddToGroupAsync(Context.ConnectionId, group, Context.ConnectionAborted);
            await base.OnConnectedAsync();
        }
        // Retain the legacy signature without granting client broadcast rights.
        public Task SendMessage(string user, string message) =>
            Task.FromException(new HubException("Notifications are generated by the server."));
    }
}
