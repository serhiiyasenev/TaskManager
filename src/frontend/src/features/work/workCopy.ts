export const workCopy = { uk, en };
export function useWorkCopy() {
  const selection = useLocale();
  const copy = workCopy[selection.locale];
  function text(key: keyof typeof uk, values: Record<string, string | number>) {
    let template: string = copy[key];
    const count = Number(values.count);
    if (key === 'taskCount' && Number.isFinite(count)) {
      const category = new Intl.PluralRules(selection.intlLocale, {
        minimumFractionDigits: Number.isInteger(count) ? 0 : 1, maximumFractionDigits: 20,
      }).select(count);
      const forms: Partial<Record<Intl.LDMLPluralRule, string>> = {
        one: copy.taskCountOne, few: copy.taskCountFew, other: copy.taskCountOther,
      };
      template = forms[category] ?? copy.taskCount;
    }
    return template.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
  }
  return { ...selection, copy, text };
}
